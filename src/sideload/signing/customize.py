"""Sideloadly-style app customization for sign and install.

Every option is a small typed function over an AppBundle (plus one
driver over the IPABundle inventory) so the CLI stays a thin adapter:

    set_display_name          CFBundleDisplayName + CFBundleName
    remove_plugins            PlugIns/*.appex and Watch content
    load_entitlements          user supplied entitlements plist
    split_extra_entitlements  profile granted check for those keys
    set_minimum_os_version    MinimumOSVersion (and DeploymentTarget
                              when the plist already carries it)
    set_supported_devices     UISupportedDevices
    replace_app_icon          icon PNGs via the macOS sips tool
    build_customization       flag validation into AppCustomization
    apply_customization       safe ordering driver

Ordering guarantees (cli._sign_pipeline relies on both):

    1. Plugin removal runs before any App ID, profile, or entitlement
       is requested, and the bundle inventory is recomputed immediately
       after it, so a removed extension is never provisioned, never
       signed, and never reaches the output IPA.
    2. Every remaining Info.plist edit and the icon replacement run
       before signing seals CodeResources; nothing may touch a bundle
       after the outer signature.

Entitlement contract for --entitlements: the user plist is merged
through build_entitlements' "extra" parameter, which that function
applies WITHOUT the profile grant check (the psychic paper semantics).
To keep the documented "profile wins" rule, the caller must pre-filter
with split_extra_entitlements: keys the profile does not grant are
reported as dropped (a warning, or an error together with
--strict-entitlements) and only granted keys flow into "extra". Keys
the resign pipeline manages itself (application-identifier,
get-task-allow, com.apple.developer.team-identifier,
keychain-access-groups) are always rewritten from the profile
afterwards, whatever the user plist says.

Icon support is best effort by design: icon files are located through
the CFBundleIcons / CFBundleIconFiles / CFBundleIconFile references and
the pixel size comes from the file name (AppIcon60x60@2x means a 120
pixel square) or from measuring the existing file with sips. Every
written file keeps a name the plist already references, so no plist
entry needs rewriting. Icons inside compiled asset catalogs
(Assets.car) cannot be regenerated by sips, and when Info.plist has no
recognizable icon reference at all the flag fails with a clear error
rather than corrupting the plist.
"""

from __future__ import annotations

import plistlib
import re
import shutil
import subprocess
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any

from sideload.errors import IPAError, TransportError, UsageError
from sideload.models import ProvisioningProfile
from sideload.signing.entitlements import _is_granted, _which_tool
from sideload.signing.ipa import AppBundle, IPABundle, _load_plist_dict

_SIPS_TIMEOUT = 60.0
_HINT_SIPS_MISSING = "sips ships with macOS; it should exist at /usr/bin/sips"

# Icon file name shapes, for example AppIcon60x60.png or
# AppIcon60x60@2x.png or AppIcon83.5@2x~ipad.png.
_ICON_SIZE_IN_NAME = re.compile(r"(\d+)[xX](\d+)")
_ICON_SCALE_IN_NAME = re.compile(r"@(\d+)x")

# Bundle suffixes treated as plugin content inside PlugIns.
_PLUGIN_SUFFIXES = (".appex", ".app")


# --------------------------------------------------------- Info.plist edit


def _read_info(bundle: AppBundle) -> tuple[dict[str, Any], plistlib.PlistFormat]:
    """Info.plist values plus the plist format they were stored in."""
    with open(bundle.info_plist_path, "rb") as handle:
        raw = handle.read()
    values = _load_plist_dict(raw, bundle.info_plist_path)
    fmt = plistlib.FMT_BINARY if raw.startswith(b"bplist00") else plistlib.FMT_XML
    return values, fmt


def _write_info(
    bundle: AppBundle, values: dict[str, Any], fmt: plistlib.PlistFormat
) -> None:
    with open(bundle.info_plist_path, "wb") as handle:
        plistlib.dump(values, handle, fmt=fmt)


def set_display_name(bundle: AppBundle, name: str) -> None:
    """Set CFBundleDisplayName and CFBundleName to the given name."""
    if not name:
        raise UsageError("--name needs a non-empty display name")
    values, fmt = _read_info(bundle)
    values["CFBundleDisplayName"] = name
    values["CFBundleName"] = name
    _write_info(bundle, values, fmt)


_MIN_OS_PATTERN = re.compile(r"^\d+(?:\.\d+){0,3}$")


def is_valid_os_version(version: str) -> bool:
    """True for version strings like 13, 13.0, or 13.4.1."""
    return bool(_MIN_OS_PATTERN.match(version))


def set_minimum_os_version(bundle: AppBundle, version: str) -> None:
    """Set MinimumOSVersion, and DeploymentTarget when already present.

    DeploymentTarget is only rewritten when the plist carries the key;
    it is never added, so plists without it stay untouched.
    """
    if not is_valid_os_version(version):
        raise UsageError(f"--min-os expects a version like 13.0, got {version!r}")
    values, fmt = _read_info(bundle)
    values["MinimumOSVersion"] = version
    if "DeploymentTarget" in values:
        values["DeploymentTarget"] = version
    _write_info(bundle, values, fmt)


def set_supported_devices(bundle: AppBundle, devices: Sequence[str]) -> None:
    """Replace UISupportedDevices with the given device identifiers."""
    cleaned = [device.strip() for device in devices if device.strip()]
    if not cleaned:
        raise UsageError("--supported-devices needs at least one device identifier")
    values, fmt = _read_info(bundle)
    values["UISupportedDevices"] = cleaned
    _write_info(bundle, values, fmt)


# --------------------------------------------------------- plugin removal


def remove_plugins(bundle: AppBundle) -> list[str]:
    """Delete PlugIns/*.appex (and any Watch content) from the bundle.

    Returns the names of the removed items so the caller can report
    them. Removal MUST run before App IDs, profiles, and entitlements
    are requested and before signing; the caller recomputes its bundle
    inventory right after this returns.
    """
    removed: list[str] = []
    plugins_dir = bundle.root / "PlugIns"
    if plugins_dir.is_dir() and not plugins_dir.is_symlink():
        for entry in sorted(plugins_dir.iterdir()):
            if entry.suffix not in _PLUGIN_SUFFIXES:
                continue
            if entry.is_symlink() or not entry.is_dir():
                entry.unlink(missing_ok=True)
            else:
                shutil.rmtree(entry)
            removed.append(entry.name)
        if not any(plugins_dir.iterdir()):
            plugins_dir.rmdir()
    watch_dir = bundle.root / "Watch"
    if watch_dir.is_dir() and not watch_dir.is_symlink():
        shutil.rmtree(watch_dir)
        removed.append(watch_dir.name)
    return removed


# --------------------------------------------------- custom entitlements


def load_entitlements(path: Path) -> dict[str, object]:
    """Load a user supplied entitlements plist (XML or binary).

    UsageError covers the bad-input cases: a missing file, an
    unreadable plist, or a plist whose root is not a dictionary.
    """
    path = Path(path)
    if not path.is_file():
        raise UsageError(f"entitlements file not found: {path}")
    raw = path.read_bytes()
    try:
        parsed: object = plistlib.loads(raw)
    except (plistlib.InvalidFileException, ValueError) as exc:
        raise UsageError(f"{path} is not a readable plist: {exc}") from exc
    if not isinstance(parsed, dict):
        raise UsageError(f"{path} must be a plist dictionary of entitlements")
    return dict(parsed)


def split_extra_entitlements(
    profile: ProvisioningProfile, requested: dict[str, object]
) -> tuple[dict[str, object], list[str]]:
    """Split user entitlements into profile granted and dropped keys.

    build_entitlements merges its extra parameter without checking the
    profile, so this is the gate that keeps the documented rule: only
    granted keys may flow into extra. Returns (granted, dropped) where
    dropped is sorted and may be empty; the caller prints a warning or
    (with --strict-entitlements) raises EntitlementsError for it.
    """
    base: dict[str, object] = dict(profile.entitlements)
    granted = {
        key: value for key, value in requested.items() if _is_granted(base, key)
    }
    dropped = sorted(key for key in requested if key not in granted)
    return granted, dropped


# ------------------------------------------------------- icon replacement


def _encoded_pixel_edge(stem: str) -> int | None:
    """The pixel edge encoded in an icon file name, when present.

    AppIcon60x60 means 60 pixels, AppIcon60x60@2x means 120, and
    AppIcon76x76~ipad means 76. Returns None when the name carries no
    readable size; the caller then measures the existing file.
    """
    match = _ICON_SIZE_IN_NAME.search(stem)
    if match is None:
        return None
    edge = int(match.group(1))
    scale_match = _ICON_SCALE_IN_NAME.search(stem)
    scale = int(scale_match.group(1)) if scale_match is not None else 1
    return edge * scale


def _run_sips(command: list[str]) -> subprocess.CompletedProcess[bytes]:
    """Run sips once with captured output; wrapped as IPAError."""
    try:
        return subprocess.run(
            command, check=False, capture_output=True, timeout=_SIPS_TIMEOUT
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise IPAError(f"could not run sips: {exc}") from exc


def _sips_dimensions(sips: str, path: Path) -> tuple[int, int] | None:
    """Measure a PNG with sips; None when sips cannot read it."""
    result = _run_sips([sips, "-g", "pixelWidth", "-g", "pixelHeight", str(path)])
    if result.returncode != 0:
        return None
    text = result.stdout.decode("utf-8", "replace")
    width = _parse_sips_property(text, "pixelWidth")
    height = _parse_sips_property(text, "pixelHeight")
    if width is None or height is None:
        return None
    return width, height


def _parse_sips_property(text: str, name: str) -> int | None:
    for line in text.splitlines():
        key, separator, value = line.partition(":")
        if separator and key.strip() == name:
            try:
                return int(value.strip())
            except ValueError:
                return None
    return None


def _sips_resample(sips: str, source: Path, target: Path, edge: int) -> None:
    """Resample source into a square edge x edge PNG at target."""
    result = _run_sips([sips, "-z", str(edge), str(edge), str(source), "--out", str(target)])
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", "replace").strip()
        raise IPAError(
            f"sips could not turn {source} into a {edge}x{edge} icon"
            + (f": {detail}" if detail else "")
        )


def _collect_icon_names(values: dict[str, Any]) -> list[str]:
    """Every icon reference in Info.plist, in a stable order.

    Covers CFBundleIcons > CFBundlePrimaryIcon > CFBundleIconFiles plus
    its CFBundleIconName (the compiled asset catalog name; including it
    makes a pure asset catalog app report the catalog limitation
    instead of a bare "nothing found"), the top level CFBundleIconFiles
    list, and the legacy single CFBundleIconFile string.
    """
    names: list[str] = []

    def _extend(entry: object) -> None:
        if isinstance(entry, list):
            names.extend(item for item in entry if isinstance(item, str) and item)

    def _add(entry: object) -> None:
        if isinstance(entry, str) and entry:
            names.append(entry)

    icons = values.get("CFBundleIcons")
    if isinstance(icons, dict):
        primary = icons.get("CFBundlePrimaryIcon")
        if isinstance(primary, dict):
            _extend(primary.get("CFBundleIconFiles"))
            _add(primary.get("CFBundleIconName"))
    _extend(values.get("CFBundleIconFiles"))
    _add(values.get("CFBundleIconFile"))

    unique: list[str] = []
    for name in names:
        if name not in unique:
            unique.append(name)
    return unique


def _icon_stem(name: str) -> str:
    """The reference without a trailing .png extension."""
    return name[:-4] if name.lower().endswith(".png") else name


def _icon_path_candidates(bundle: AppBundle, name: str) -> list[Path]:
    """Every in-bundle path one icon reference can mean.

    A reference with a slash is a relative path into the bundle. A
    bare name also covers the @2x/@3x scale variants iOS resolves on
    its own, plus a possible missing .png extension.
    """
    root = bundle.root
    if "/" in name or "\\" in name:
        return [_safe_icon_join(root, name)]
    stem = _icon_stem(name)
    candidates = [f"{stem}.png", f"{stem}@2x.png", f"{stem}@3x.png", stem]
    unique: list[str] = []
    for candidate in candidates:
        if candidate not in unique:
            unique.append(candidate)
    return [root / candidate for candidate in unique]


def _safe_icon_join(root: Path, relative: str) -> Path:
    """Join a relative icon reference, refusing traversal escapes."""
    pure = PurePosixPath(relative)
    if pure.is_absolute() or not pure.parts or any(
        part in {"..", ""} for part in pure.parts
    ):
        raise IPAError(f"unsafe icon reference in Info.plist: {relative!r}")
    return root.joinpath(*pure.parts)


def _inside_bundle(bundle: AppBundle, target: Path) -> bool:
    """True when target resolves inside the bundle root."""
    try:
        return target.resolve().is_relative_to(bundle.root.resolve())
    except OSError:
        return False


def _find_icon_files(bundle: AppBundle, name: str) -> list[Path]:
    """Every existing file one plist icon reference can mean.

    A bare name resolves to all its present scale variants
    (name.png, name@2x.png, name@3x.png), because iOS picks the
    variant itself and a stale @2x file would survive otherwise.
    The subdirectory fallback matches by file name only and keeps the
    first hit, so unrelated same named files are never touched.
    """
    candidates = [
        candidate
        for candidate in _icon_path_candidates(bundle, name)
        if _inside_bundle(bundle, candidate) and candidate.is_file()
    ]
    if candidates:
        return candidates
    wanted = {candidate.name for candidate in _icon_path_candidates(bundle, name)}
    for path in bundle._iter_files():
        if path.name in wanted and _inside_bundle(bundle, path):
            return [path]
    return []


def _created_icon_target(bundle: AppBundle, name: str) -> Path | None:
    """A root level PNG for a size-named reference with no file.

    When the plist references AppIcon76x76 but the bundle never
    shipped the loose PNG, the icon is created at that size; the plist
    already references the name, so no entry needs rewriting.
    """
    if "/" in name or "\\" in name:
        return None
    stem = _icon_stem(name)
    if _encoded_pixel_edge(stem) is None:
        return None
    return bundle.root / f"{stem}.png"


def replace_app_icon(bundle: AppBundle, source_png: Path) -> list[str]:
    """Replace the bundle's icon PNGs with resamples of source_png.

    Every icon file referenced by CFBundleIcons / CFBundleIconFiles /
    CFBundleIconFile is regenerated with the macOS sips tool at the
    pixel size its name encodes (AppIcon60x60@2x becomes 120x120) or,
    when the name encodes nothing, the size of the existing file. All
    present scale variants of a reference (name.png, name@2x.png,
    name@3x.png) are regenerated, because iOS picks the variant
    itself. Every written file keeps a name the plist already
    references, so no plist entry is rewritten and the plist is never
    corrupted.

    Returns the replaced paths relative to the bundle root. Raises
    UsageError when the source file is missing, TransportError when
    sips is unavailable, and IPAError when the bundle has no
    recognizable icon references (for example a compiled asset
    catalog) or sips rejects the source image.
    """
    source_png = Path(source_png)
    if not source_png.is_file():
        raise UsageError(f"icon file not found: {source_png}")
    sips = _which_tool("sips")
    if sips is None:
        raise TransportError(
            "the sips tool was not found", hint=_HINT_SIPS_MISSING
        )
    values, _fmt = _read_info(bundle)
    names = _collect_icon_names(values)
    if not names:
        raise IPAError(
            f"{bundle.root.name} has no app icon reference sideload could "
            "replace (CFBundleIcons/CFBundleIconFiles)",
            hint=(
                "icon replacement works with loose PNG icon files; icons "
                "inside compiled asset catalogs (Assets.car) are not supported"
            ),
        )
    replaced: list[str] = []
    seen: set[Path] = set()
    for name in names:
        targets = _find_icon_files(bundle, name)
        if not targets:
            created = _created_icon_target(bundle, name)
            if created is None:
                continue
            targets = [created]
        for target in targets:
            if target in seen:
                continue
            seen.add(target)
            edge = _encoded_pixel_edge(target.stem)
            if edge is None:
                measured = _sips_dimensions(sips, target)
                if measured is None:
                    raise IPAError(
                        f"sips could not measure the existing icon {target}",
                        hint="the reference names no size and the file is unreadable",
                    )
                edge = max(measured)
            _sips_resample(sips, source_png, target, edge)
            replaced.append(target.relative_to(bundle.root).as_posix())
    if not replaced:
        raise IPAError(
            f"{bundle.root.name} stores its icon in a compiled asset catalog "
            "(Assets.car) that sips cannot regenerate",
            hint=(
                "icon replacement needs loose PNG icon files; repack the app "
                "without a compiled asset catalog"
            ),
        )
    return replaced


# ------------------------------------------------------------- pipeline


@dataclass(frozen=True)
class AppCustomization:
    """Validated customization flags for one sign run.

    None (or False) means no change; an empty entitlements dict is
    treated as no change too.
    """

    display_name: str | None = None
    remove_plugins: bool = False
    extra_entitlements: dict[str, object] | None = None
    minimum_os_version: str | None = None
    supported_devices: tuple[str, ...] | None = None
    icon_source: Path | None = None


def build_customization(
    *,
    name: str | None,
    remove_plugins: bool,
    entitlements_path: str | None,
    min_os: str | None,
    supported_devices: Sequence[str] | None,
    icon_path: str | None,
) -> AppCustomization:
    """Validate the CLI flags into an AppCustomization.

    Everything a bad flag can reject happens here, before any Apple
    side effect: a missing entitlements or icon file, an unreadable
    entitlements plist, a malformed --min-os value, an empty display
    name, or an empty --supported-devices list all raise UsageError.
    """
    if name is not None and not name:
        raise UsageError("--name needs a non-empty display name")
    extra_entitlements: dict[str, object] | None = None
    if entitlements_path is not None:
        loaded = load_entitlements(Path(entitlements_path).expanduser())
        extra_entitlements = loaded if loaded else None
    if min_os is not None and not is_valid_os_version(min_os):
        raise UsageError(f"--min-os expects a version like 13.0, got {min_os!r}")
    devices: tuple[str, ...] | None = None
    if supported_devices is not None:
        cleaned = tuple(
            device.strip() for device in supported_devices if device.strip()
        )
        if not cleaned:
            raise UsageError("--supported-devices needs at least one device identifier")
        devices = cleaned
    icon_source: Path | None = None
    if icon_path is not None:
        icon_source = Path(icon_path).expanduser()
        if not icon_source.is_file():
            raise UsageError(f"icon file not found: {icon_source}")
    return AppCustomization(
        display_name=name,
        remove_plugins=remove_plugins,
        extra_entitlements=extra_entitlements,
        minimum_os_version=min_os,
        supported_devices=devices,
        icon_source=icon_source,
    )


def apply_customization(bundle: IPABundle, custom: AppCustomization) -> list[str]:
    """Apply every customization to the extracted IPA in place.

    Ordering guarantees:

    - plugin removal first, with the bundle inventory recomputed right
      after it, so the caller's App ID / profile / entitlement /
      signing loops never see a removed extension;
    - all remaining Info.plist edits and the icon replacement after
      that, always before signing seals CodeResources.

    Returns short human readable notes for the CLI to print; an empty
    list means nothing was requested (or nothing matched).
    """
    notes: list[str] = []
    main_bundle = bundle.main_bundle
    if custom.remove_plugins:
        removed = remove_plugins(main_bundle)
        if removed:
            bundle.all_bundles = [
                bundle.main_bundle,
                *bundle.main_bundle.nested_bundles(),
            ]
            for name in removed:
                notes.append(f"removed extension: {name}")
    if custom.display_name is not None:
        set_display_name(main_bundle, custom.display_name)
        notes.append(f"name: {custom.display_name}")
    if custom.minimum_os_version is not None:
        set_minimum_os_version(main_bundle, custom.minimum_os_version)
        notes.append(f"minimum os version: {custom.minimum_os_version}")
    if custom.supported_devices is not None:
        set_supported_devices(main_bundle, custom.supported_devices)
        notes.append("supported devices: " + ", ".join(custom.supported_devices))
    if custom.icon_source is not None:
        replaced = replace_app_icon(main_bundle, custom.icon_source)
        for relative in replaced:
            notes.append(f"icon replaced: {relative}")
    return notes
